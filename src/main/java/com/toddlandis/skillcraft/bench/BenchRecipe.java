package com.toddlandis.skillcraft.bench;

import java.util.ArrayList;
import java.util.Comparator;
import java.util.List;
import java.util.Map;

import com.mojang.serialization.Codec;
import com.mojang.serialization.codecs.RecordCodecBuilder;
import com.toddlandis.skillcraft.registry.ModDataMaps;
import com.toddlandis.skillcraft.skill.XpTable;

import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.resources.ResourceKey;
import net.minecraft.world.item.Item;
import net.minecraft.world.item.ItemStack;
import net.minecraft.world.item.crafting.Ingredient;

// A recipe made at a bench. Stored as a data map on the item it produces:
// data/skillcraft/data_maps/item/bench_recipes.json (generated by scripts/gen_bench_recipes.sh)
//   station     - "anvil" (Smithing) or "crafting_bench" (Crafting)
//   level / xp  - skill level needed and XP per item
//   time        - ticks per item (20 = 1 second)
//   count       - items produced per craft
//   ingredients - [{"item": "minecraft:iron_ingot" or "#tag", "count": 3}, ...]
//   keep_components_from - optional ingredient index whose enchantments/name/damage carry over
//                          to the result (used for netherite upgrades); -1 = none
public record BenchRecipe(Station station, int level, double xp, int time, int count, List<Part> ingredients, int keepComponentsFrom) {
    public record Part(Ingredient ingredient, int count) {
        public static final Codec<Part> CODEC = RecordCodecBuilder.create(instance -> instance.group(
                Ingredient.CODEC.fieldOf("item").forGetter(Part::ingredient),
                Codec.intRange(1, 64).optionalFieldOf("count", 1).forGetter(Part::count)
        ).apply(instance, Part::new));
    }

    public static final Codec<BenchRecipe> CODEC = RecordCodecBuilder.create(instance -> instance.group(
            Station.CODEC.fieldOf("station").forGetter(BenchRecipe::station),
            Codec.intRange(1, XpTable.MAX_LEVEL).fieldOf("level").forGetter(BenchRecipe::level),
            Codec.DOUBLE.fieldOf("xp").forGetter(BenchRecipe::xp),
            Codec.intRange(1, 20 * 60 * 10).fieldOf("time").forGetter(BenchRecipe::time),
            Codec.intRange(1, 64).optionalFieldOf("count", 1).forGetter(BenchRecipe::count),
            Part.CODEC.listOf().fieldOf("ingredients").forGetter(BenchRecipe::ingredients),
            Codec.INT.optionalFieldOf("keep_components_from", -1).forGetter(BenchRecipe::keepComponentsFrom)
    ).apply(instance, BenchRecipe::new));

    public static BenchRecipe get(Item item) {
        return BuiltInRegistries.ITEM.getResourceKey(item).map(key -> BuiltInRegistries.ITEM.getData(ModDataMaps.BENCH_RECIPES, key)).orElse(null);
    }

    // Every recipe for a station, sorted by level then name
    public static List<Item> forStation(Station station) {
        List<Item> items = new ArrayList<>();
        for (Map.Entry<ResourceKey<Item>, BenchRecipe> entry : BuiltInRegistries.ITEM.getDataMap(ModDataMaps.BENCH_RECIPES).entrySet()) {
            if (entry.getValue().station() == station) items.add(BuiltInRegistries.ITEM.getValueOrThrow(entry.getKey()));
        }
        items.sort(Comparator.comparingInt((Item item) -> get(item).level()).thenComparing(item -> BuiltInRegistries.ITEM.getKey(item).toString()));
        return items;
    }

    // How many times this can be made from a pool of items (e.g. a player's inventory)
    public int maxCrafts(List<ItemStack> pool) {
        int max = Integer.MAX_VALUE;
        for (Part part : ingredients) {
            int available = 0;
            for (ItemStack stack : pool) {
                if (!stack.isEmpty() && part.ingredient().test(stack)) available += stack.getCount();
            }
            max = Math.min(max, available / part.count());
        }
        return max;
    }

    // Removes ingredients for `times` crafts from the pool; returns exactly what was removed
    public List<ItemStack> take(List<ItemStack> pool, int times) {
        List<ItemStack> taken = new ArrayList<>();
        for (Part part : ingredients) {
            int needed = part.count() * times;
            for (ItemStack stack : pool) {
                if (needed <= 0) break;
                if (stack.isEmpty() || !part.ingredient().test(stack)) continue;
                int used = Math.min(needed, stack.getCount());
                taken.add(stack.copyWithCount(used));
                stack.shrink(used);
                needed -= used;
            }
        }
        return taken;
    }
}
